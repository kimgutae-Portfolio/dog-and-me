     or v_order.terms_version is distinct from '2026-07-21'
     or v_order.privacy_version is distinct from '2026-07-21'
     or v_order.ai_notice_version is distinct from '2026-07-21' then raise exception 'current consent record required before video production'; end if;
  if p_storage_path not like v_order.user_id::text || '/' || v_order.id::text || '/%' then raise exception 'invalid storage path'; end if;

  if p_category = 'review_video' and v_order.status not in ('production', 'revision_requested', 'customer_review') then
    raise exception 'review video cannot be uploaded in current status';
  end if;
  if p_category = 'final_video' then
    if v_order.status <> 'quality_check' then raise exception 'final video requires quality_check status'; end if;
    if v_order.customer_approved_at is null or v_order.customer_approved_review_asset_id is null then
      raise exception 'customer approval required before final video';
    end if;
    if exists (select 1 from public.revision_requests where order_id = p_order_id and status = 'open') then
      raise exception 'open revision must be resolved before final video';
    end if;
  end if;

  insert into public.assets(order_id, user_id, category, storage_path, original_filename, mime_type, file_size)
  values (p_order_id, v_order.user_id, p_category, p_storage_path, p_original_filename, p_mime_type, p_file_size)
  returning id into v_asset_id;

  if p_category = 'review_video' then
    update public.orders
    set status = 'customer_review',
        customer_approved_at = null,
        customer_approved_by = null,
        customer_approved_review_asset_id = null,
        stage_updated_at = now()
    where id = p_order_id;
  end if;

  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (
    p_order_id,
    auth.uid(),
    case when p_category = 'review_video' then 'review_video_uploaded' else 'final_video_uploaded' end,
    jsonb_build_object('asset_id', v_asset_id, 'filename', p_original_filename, 'file_size', p_file_size)
  );
  return v_asset_id;
end;
$$;

create or replace function public.admin_deliver_order(
  p_order_id uuid,
  p_asset_id uuid,
  p_title text,
  p_customer_message text
)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  if not public.is_admin() then raise exception 'admin required'; end if;
  if coalesce(trim(p_title), '') = '' then raise exception 'delivery title required'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order not found'; end if;
  if v_order.payment_status <> 'paid' then raise exception 'payment must be confirmed before delivery'; end if;
  if v_order.status <> 'quality_check' then raise exception 'delivery requires quality_check status'; end if;
  if v_order.customer_approved_at is null or v_order.customer_approved_review_asset_id is null then
    raise exception 'customer approval required before delivery';
  end if;
  if exists (select 1 from public.revision_requests where order_id = p_order_id and status = 'open') then
    raise exception 'open revision must be resolved before delivery';
  end if;
  if not exists (
    select 1 from public.assets where id = p_asset_id and order_id = p_order_id and category = 'final_video'
  ) then raise exception 'final video asset not found'; end if;

  insert into public.deliveries(order_id, final_asset_id, title, customer_message, delivered_at)
  values (p_order_id, p_asset_id, trim(p_title), nullif(trim(coalesce(p_customer_message, '')), ''), now())
  on conflict (order_id) do update
  set final_asset_id = excluded.final_asset_id,
      title = excluded.title,
      customer_message = excluded.customer_message,
      delivered_at = now();

  update public.orders set status = 'delivered', stage_updated_at = now() where id = p_order_id;
  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (
    p_order_id,
    auth.uid(),
    'order_delivered',
    jsonb_build_object(
      'asset_id', p_asset_id,
      'title', trim(p_title),
      'customer_approved_at', v_order.customer_approved_at,
      'approved_review_asset_id', v_order.customer_approved_review_asset_id
    )
  );
end;
$$;

create or replace function public.expire_memory_order_draft(p_order_id uuid)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  update public.orders
  set status = 'cancelled', stage_updated_at = now(), campaign_id = null,
      personality = '[]'::jsonb,
      first_meeting = null,
      favorite_memory = null,
      message_to_pet = null,
      avoid_notes = null,
      admin_notes = null,
      selected_concept_slot = null
  where id = p_order_id
    and status = 'awaiting_materials'
    and draft_expires_at is not null
    and draft_expires_at <= now();
  if not found then raise exception 'expired draft not found'; end if;

  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (p_order_id, null, 'draft_expired', jsonb_build_object('expired_at', now()));
end;
$$;

