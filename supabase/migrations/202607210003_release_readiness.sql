alter table public.orders
  add column if not exists consented_at timestamptz,
  add column if not exists terms_version text,
  add column if not exists privacy_version text,
  add column if not exists external_ai_consent_at timestamptz,
  add column if not exists ai_notice_version text,
  add column if not exists customer_approved_at timestamptz,
  add column if not exists customer_approved_by uuid references public.profiles(id) on delete set null,
  add column if not exists customer_approved_review_asset_id uuid references public.assets(id) on delete set null,
  add column if not exists draft_expires_at timestamptz;

update public.orders
set draft_expires_at = created_at + interval '7 days'
where status = 'awaiting_materials' and draft_expires_at is null;

drop index if exists public.orders_expired_drafts_idx;
create index orders_expired_drafts_idx
on public.orders(draft_expires_at)
where draft_expires_at is not null and status in ('awaiting_materials', 'cancelled');

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  target_user_id uuid references public.profiles(id) on delete set null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.security_events enable row level security;

drop policy if exists security_events_admin_select on public.security_events;
create policy security_events_admin_select on public.security_events for select to authenticated
using (public.is_admin());

