create or replace function public.submit_memory_order(p_order_id uuid)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_photo_count integer;
  v_launch_count integer;
  v_price integer;
  v_campaign text;
begin
  select * into v_order
  from public.orders
  where id = p_order_id and user_id = auth.uid()
  for update;

  if not found or v_order.status <> 'awaiting_materials' then raise exception 'order not found or cannot be submitted'; end if;
  if v_order.draft_expires_at is not null and v_order.draft_expires_at <= now() then raise exception 'draft expired'; end if;
  if coalesce(trim(v_order.age_text), '') = '' then raise exception 'age required'; end if;
  if jsonb_typeof(v_order.personality) <> 'array' then raise exception 'personality required'; end if;
  if jsonb_array_length(v_order.personality) < 1 then raise exception 'personality required'; end if;
  if coalesce(trim(v_order.favorite_memory), '') = '' then raise exception 'favorite memory required'; end if;
  if coalesce(trim(v_order.message_to_pet), '') = '' then raise exception 'message to pet required'; end if;
  if v_order.consented_at is null or v_order.external_ai_consent_at is null
     or v_order.terms_version is distinct from '2026-07-21'
     or v_order.privacy_version is distinct from '2026-07-21'
     or v_order.ai_notice_version is distinct from '2026-07-21' then raise exception 'current consent record required'; end if;

  select count(*)::integer into v_photo_count
  from public.assets
  where order_id = p_order_id and user_id = auth.uid() and category = 'source_image';
  if v_photo_count < 5 then raise exception 'at least 5 source images are required'; end if;

  perform pg_advisory_xact_lock(hashtext('wan-memory-launch-monitor-10'));
  select count(*)::integer into v_launch_count
  from public.orders
  where campaign_id = 'launch-monitor-10' and status not in ('awaiting_materials', 'cancelled');

  if v_launch_count < 10 then
    v_price := 24800;
    v_campaign := 'launch-monitor-10';
  else
    v_price := v_order.regular_price;
    v_campaign := null;
  end if;

  update public.orders
  set status = 'materials_submitted', quoted_price = v_price, campaign_id = v_campaign,
      stage_updated_at = now(), draft_expires_at = null
  where id = p_order_id;

  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (
    p_order_id,
    auth.uid(),
    'materials_submitted',
    jsonb_build_object(
      'photo_count', v_photo_count,
      'quoted_price', v_price,
      'campaign_id', v_campaign,
      'consented_at', v_order.consented_at,
      'terms_version', v_order.terms_version,
      'privacy_version', v_order.privacy_version,
      'ai_notice_version', v_order.ai_notice_version
    )
  );
end;
$$;

create or replace function public.request_order_revision(p_order_id uuid, p_category text, p_body text)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_revision_number integer;
begin
  if coalesce(trim(p_body), '') = '' then raise exception 'revision body required'; end if;
  select * into v_order from public.orders where id = p_order_id and user_id = auth.uid() for update;
  if not found or v_order.status <> 'customer_review' then raise exception 'order not found or revision unavailable'; end if;
  if v_order.revision_used >= v_order.revision_limit then raise exception 'revision limit reached'; end if;
  if exists (select 1 from public.revision_requests where order_id = p_order_id and status = 'open') then
    raise exception 'previous revision is still open';
  end if;

  v_revision_number := v_order.revision_used + 1;
  insert into public.revision_requests(order_id, user_id, category, body)
  values (p_order_id, auth.uid(), coalesce(nullif(trim(p_category), ''), 'その他'), trim(p_body));

  update public.orders
  set status = 'revision_requested', revision_used = v_revision_number,
      customer_approved_at = null, customer_approved_by = null,
      customer_approved_review_asset_id = null, stage_updated_at = now()
  where id = p_order_id;

  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (
    p_order_id,
    auth.uid(),
    'revision_requested',
    jsonb_build_object('category', p_category, 'revision_number', v_revision_number, 'revision_limit', v_order.revision_limit)
  );
end;
$$;

create or replace function public.customer_approve_review(p_order_id uuid)
returns timestamptz
language plpgsql
security definer set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_review_asset_id uuid;
  v_approved_at timestamptz := now();
begin
  select * into v_order
  from public.orders
  where id = p_order_id and user_id = auth.uid()
  for update;

  if not found or v_order.status <> 'customer_review' then raise exception 'review approval unavailable'; end if;
  if v_order.payment_status <> 'paid' then raise exception 'payment must be confirmed before approval'; end if;
  if v_order.consented_at is null or v_order.external_ai_consent_at is null
     or v_order.terms_version is distinct from '2026-07-21'
     or v_order.privacy_version is distinct from '2026-07-21'
     or v_order.ai_notice_version is distinct from '2026-07-21' then raise exception 'current consent record required'; end if;
  if exists (select 1 from public.revision_requests where order_id = p_order_id and status = 'open') then
    raise exception 'open revision must be resolved before approval';
  end if;

  select id into v_review_asset_id
  from public.assets
  where order_id = p_order_id and category = 'review_video'
  order by created_at desc, id desc
  limit 1;
  if v_review_asset_id is null then raise exception 'review video not found'; end if;

  update public.orders
  set status = 'quality_check',
      customer_approved_at = v_approved_at,
      customer_approved_by = auth.uid(),
      customer_approved_review_asset_id = v_review_asset_id,
      stage_updated_at = now()
  where id = p_order_id;

  insert into public.order_events(order_id, actor_id, event_type, payload)
  values (
    p_order_id,
    auth.uid(),
    'customer_review_approved',
    jsonb_build_object('review_asset_id', v_review_asset_id, 'approved_at', v_approved_at)
  );
  return v_approved_at;
end;
$$;

