create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_trusted_sql boolean;
  v_bootstrap_allowed boolean;
begin
  if new.role is not distinct from old.role then return new; end if;

  v_trusted_sql := session_user in ('postgres', 'supabase_admin');
  v_bootstrap_allowed :=
    old.role = 'customer'
    and new.role = 'admin'
    and v_trusted_sql
    and not exists (select 1 from public.profiles where role = 'admin');

  if not public.is_admin() and not v_trusted_sql then
    raise exception 'role cannot be changed';
  end if;

  insert into public.security_events(actor_id, target_user_id, event_type, payload)
  values (
    auth.uid(),
    new.id,
    'profile_role_changed',
    jsonb_build_object('from', old.role, 'to', new.role, 'bootstrap', v_bootstrap_allowed, 'trusted_sql', v_trusted_sql, 'session_user', session_user)
  );
  return new;
end;
$$;

create or replace function public.bootstrap_first_admin(p_email text)
returns uuid
language plpgsql
security definer set search_path = public
as $$
declare
  v_profile_id uuid;
begin
  if session_user not in ('postgres', 'supabase_admin') then
    raise exception 'bootstrap is available only from a trusted SQL session';
  end if;
  if exists (select 1 from public.profiles where role = 'admin') then
    raise exception 'an admin already exists';
  end if;

  select id into v_profile_id
  from public.profiles
  where lower(email) = lower(trim(p_email))
  limit 1;
  if v_profile_id is null then raise exception 'profile not found; sign up first'; end if;

  update public.profiles set role = 'admin' where id = v_profile_id;
  return v_profile_id;
end;
$$;

revoke all on function public.bootstrap_first_admin(text) from public, anon, authenticated;

